result=core.decode({dims:[1,5,8400],data},{x:20,y:30,width:320,height:320,full:false},{left:0,top:0,ratio:2},1,.7,{width:640,height:485});
assert.equal(result.length,1);
assert.equal(result[0].x1,170);
assert.equal(result[0].y1,175);
assert.throws(()=>core.decode({dims:[1,6,8400],data},{},{},1,.7,{}));
