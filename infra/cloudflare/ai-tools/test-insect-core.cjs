const assert=require('node:assert/strict');
const core=require('../ai/insect-core.js');
const box=(confidence=.8,extra={})=>({x1:10,y1:20,x2:30,y2:40,confidence,classIndex:0,margin:.5,...extra});
let result=core.fuse([],[],100,100);
assert.equal(result.total_count,0);
result=core.fuse([box()],[],100,100);
assert.equal(result.unknown_count,1);
assert.equal(result.detections[0].pest_code,'unknown');
const sensitive=core.fuse([box(.075)],[box(.65)],100,100);
assert.equal(sensitive.total_count,1,'low detector scores must survive in recall mode');
assert.equal(sensitive.unknown_count,1,'a low detector threshold must not lower the species identification threshold');
assert.equal(core.fuse([],[box(.69)],100,100).total_count,0,'weak species boxes alone must not create insects');
assert.equal(core.fuse([],[box(.9,{margin:.1})],100,100).total_count,0,'ambiguous species alone cannot create insects');
result=core.fuse([box(.8)],[box(.9)],100,100);
assert.equal(result.total_count,1);
assert.equal(result.identified_count,1);
assert.equal(result.detections[0].pest_code,core.classes[0]);
result=core.fuse([box(.85)],[box(.9,{margin:.1})],100,100);
assert.equal(result.unknown_count,1);
result=core.fuse([box(.85),box(.7,{x1:11,x2:31})],[box(.9),box(.75,{x1:60,x2:80})],100,100);
assert.equal(result.total_count,2,'overlapping tiles merge, independent known target survives');
assert.equal(result.total_count,result.identified_count+result.unknown_count);
assert.equal(core.makeTiles(640,485).length,7);
assert.equal(core.makeTiles(200,200).length,1);
