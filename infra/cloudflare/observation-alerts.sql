CREATE TABLE IF NOT EXISTS observation_profile (
  id INTEGER PRIMARY KEY CHECK(id=1),
  crop_id TEXT NOT NULL CHECK(crop_id IN ('guava','pomegranate','durian','pear')),
  activated_at INTEGER NOT NULL,
  revision INTEGER NOT NULL DEFAULT 1
) STRICT;
INSERT OR IGNORE INTO observation_profile(id,crop_id,activated_at) VALUES(1,'guava',CAST(unixepoch()*1000 AS INTEGER));
CREATE TABLE IF NOT EXISTS observation_rules (
  crop_id TEXT NOT NULL CHECK(crop_id IN ('guava','pomegranate','durian','pear')),
  id TEXT NOT NULL CHECK(id IN ('soil_wet','humid_environment','pest_image')),
  enabled INTEGER NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
  parameters TEXT NOT NULL CHECK(json_valid(parameters)),
  updated_at INTEGER NOT NULL DEFAULT 0,
  revision INTEGER NOT NULL DEFAULT 1,
  PRIMARY KEY(crop_id,id)
) STRICT;
INSERT OR IGNORE INTO observation_rules(crop_id,id,parameters)
  SELECT crop_id,'soil_wet','{"dry_raw":null,"wet_raw":null,"wet_index":85,"hold_minutes":120,"cooldown_minutes":360}'
  FROM (SELECT 'guava' AS crop_id UNION ALL SELECT 'pomegranate' UNION ALL SELECT 'durian' UNION ALL SELECT 'pear');
INSERT OR IGNORE INTO observation_rules(crop_id,id,parameters) VALUES
  ('guava','humid_environment','{"temperature_min":25,"temperature_max":30,"humidity_min":85,"hold_minutes":60,"cooldown_minutes":360}'),
  ('pomegranate','humid_environment','{"temperature_min":25,"temperature_max":30,"humidity_min":85,"hold_minutes":60,"cooldown_minutes":360}'),
  ('durian','humid_environment','{"temperature_min":24,"temperature_max":30,"humidity_min":85,"hold_minutes":60,"cooldown_minutes":360}'),
  ('pear','humid_environment','{"temperature_min":15,"temperature_max":25,"humidity_min":85,"hold_minutes":120,"cooldown_minutes":360}');
INSERT OR IGNORE INTO observation_rules(crop_id,id,parameters)
  SELECT crop_id,'pest_image','{"min_identified":1}' FROM
  (SELECT 'guava' AS crop_id UNION ALL SELECT 'pomegranate' UNION ALL SELECT 'durian' UNION ALL SELECT 'pear');

CREATE TABLE IF NOT EXISTS image_crop_context (
  image_id TEXT PRIMARY KEY REFERENCES images(image_id) ON DELETE CASCADE,
  crop_id TEXT NOT NULL CHECK(crop_id IN ('guava','pomegranate','durian','pear'))
) STRICT;
CREATE TRIGGER IF NOT EXISTS image_crop_context_on_camera_image AFTER INSERT ON images
WHEN NEW.source='hardware'
BEGIN
  INSERT OR IGNORE INTO image_crop_context(image_id,crop_id)
    SELECT NEW.image_id,crop_id FROM observation_profile WHERE id=1;
END;

